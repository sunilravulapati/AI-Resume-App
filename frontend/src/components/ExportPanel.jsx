  const [latexCode,    setLatexCode]    = useState(''); // raw compile-ready source
  const [latexLoading, setLatexLoading] = useState(false);
  const [latexError,   setLatexError]   = useState('');

  // Clear latex code when generation mode changes so it regenerates
  useEffect(() => {
    setLatexCode('');
  }, [generationMode]);

  // Auto-generate when the latex panel is opened for the first time
  useEffect(() => {
    if (activeOption !== 'latex') return;
    if (latexCode || latexLoading) return; // already have it or in-flight

    const generate = async () => {
      setLatexLoading(true);
      setLatexError('');

      // Guard: resumeId must be present
      if (!resumeId) {
        setLatexError('Resume ID is missing — please re-open this page and try again.');
        setLatexLoading(false);
        return;
      }

      try {
        const rawUrl = import.meta.env.VITE_API_URL || 'http://localhost:4000';
        const cleanUrl = rawUrl.replace(/\/+$/, '').replace(/\/api$/, '');
        const res = await fetch(`${cleanUrl}/api/resume/generate-latex`, {
          method:      'POST',
          credentials: 'include',                           // send auth cookie
          headers:     { 'Content-Type': 'application/json' },
          body:        JSON.stringify({ resumeId, tailoredData, mode: generationMode }),
        });

        if (!res.ok) {
          const errData = await res.json().catch(() => ({}));
          throw new Error(errData?.error || `Server error ${res.status}`);
        }

        const { latex } = await res.json();

        // Strip any accidental markdown fences the model may add
        const clean = latex
          .replace(/^```(?:latex|tex)?\s*/i, '')
          .replace(/\s*```\s*$/, '')
          .trim();

        setLatexCode(clean);
      } catch (err) {
        setLatexError(err.message || 'Something went wrong. Please try again.');
      } finally {
        setLatexLoading(false);
      }
    };

    generate();
  }, [activeOption]); // eslint-disable-line react-hooks/exhaustive-deps

