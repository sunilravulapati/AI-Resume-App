// ─── Panel: Copy & Paste ──────────────────────────────────────────────────────
function CopyPanel({ tailoredData }) {
  const [copied, setCopied] = useState(false);
  const text = generateCopyText(tailoredData);

  const handleCopy = async () => {
    await copyToClipboard(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="export-panel-body">
      <div className="export-panel-toolbar">
        <span className="export-panel-toolbar-label">Plain text — paste into any editor</span>
        <CopyButton onClick={handleCopy} copied={copied} label="Copy all" copiedLabel="Copied!" />
      </div>
      <pre className="export-code-block">{text}</pre>
    </div>
  );
}

