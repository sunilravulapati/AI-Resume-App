// ─── Copy text generator ──────────────────────────────────────────────────────
export function generateCopyText(tailoredData) {
  const lines = [];
  lines.push('═══════════════════════════════════════');
  lines.push('  AI-TAILORED RESUME CONTENT');
  lines.push('  Generated by ResumeAI');
  lines.push('═══════════════════════════════════════');
  lines.push('');

  const summary = tailoredData?.summary || '';
  const skills = tailoredData?.skills || [];
  const experience = tailoredData?.experience || [];
  const projects = tailoredData?.projects || [];

  if (summary) {
    lines.push('── PROFESSIONAL SUMMARY ──────────────');
    lines.push(summary);
    lines.push('');
  }
  if (skills?.length) {
    lines.push('── TARGETED SKILLS ───────────────────');
    lines.push(
      skills.map(s => (typeof s === 'object' ? `${s.label}: ${s.value}` : String(s))).join(' • ')
    );
    lines.push('');
  }
  if (experience?.length) {
    lines.push('── TAILORED EXPERIENCE BULLETS ───────');
    lines.push('');
    for (const exp of experience) {
      lines.push(`[ ${exp.title} ]`);
      for (const bullet of exp.bullets || []) lines.push(`  • ${bullet}`);
      lines.push('');
    }
  }
  if (projects?.length) {
    lines.push('── TAILORED PROJECT BULLETS ──────────');
    lines.push('');
    for (const proj of projects) {
      lines.push(`[ ${proj.title} ]`);
      for (const bullet of proj.bullets || []) lines.push(`  • ${bullet}`);
      lines.push('');
    }
  }
  lines.push('═══════════════════════════════════════');
  return lines.join('\n');
}

// ─── Helpers ──────────────────────────────────────────────────────────────────
function copyToClipboard(text) {
  if (navigator.clipboard?.writeText) return navigator.clipboard.writeText(text);
  return new Promise(resolve => {
    const ta = document.createElement('textarea');
    ta.value = text;
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
    resolve();
  });
}

function getApiBase() {
  const raw = import.meta.env.VITE_API_URL || 'http://localhost:4000';
  return raw.replace(/\/+$/, '').replace(/\/api$/, '');
}

