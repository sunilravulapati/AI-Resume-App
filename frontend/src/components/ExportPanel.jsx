// COPY-PASTE TEXT GENERATOR
export function generateCopyText(tailoredData) {
  const lines = [];

  lines.push('═══════════════════════════════════════');
  lines.push('  AI-TAILORED RESUME CONTENT');
  lines.push('  Generated by ResumeAI');
  lines.push('═══════════════════════════════════════');
  lines.push('');

  const summary = tailoredData?.tailoredSummary || tailoredData?.summary || '';
  const skills = tailoredData?.tailoredSkills || tailoredData?.skills || [];
  
  const rawExperience = tailoredData?.tailoredExperience || tailoredData?.experience || [];
  const rawProjects = tailoredData?.projects || [];
  const mappedProjects = rawProjects.map(proj => ({
    ...proj,
    title: `Project: ${proj.title}`,
  }));
  const experience = [...rawExperience, ...mappedProjects];

  if (summary) {
    lines.push('── PROFESSIONAL SUMMARY ──────────────');
    lines.push(summary);
    lines.push('');
  }

  if (skills?.length) {
    const skillList = skills.map(s => typeof s === 'object' ? `${s.label}: ${s.value}` : String(s));
    lines.push('── TARGETED SKILLS ───────────────────');
    lines.push(skillList.join(' • '));
    lines.push('');
  }

  if (experience?.length) {
    lines.push('── TAILORED EXPERIENCE BULLETS ───────');
    lines.push('');
    for (const exp of experience) {
      lines.push(`[ ${exp.title} ]`);
      for (const bullet of exp.bullets || []) {
        lines.push(`  • ${bullet}`);
      }
      lines.push('');
    }
  }

  lines.push('═══════════════════════════════════════');
  return lines.join('\n');
}

