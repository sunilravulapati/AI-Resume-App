// ─── Panel: LaTeX ─────────────────────────────────────────────────────────────
function LatexPanel({ resumeId, tailoredData }) {
  const [tab, setTab] = useState('code');
  const [code, setCode] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);
  const generated = useRef(false);

  const generate = async () => {
    if (!resumeId) {
      setError('Resume ID is missing — please re-open this page and try again.');
      return;
    }
    setLoading(true);
    setError('');
    try {
      const res = await fetch(`${getApiBase()}/api/resume/generate-latex`, {
        method: 'POST',
        credentials: 'include',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ resumeId, tailoredData }),
      });
      if (!res.ok) {
        const d = await res.json().catch(() => ({}));
        throw new Error(d?.error || `Server error ${res.status}`);
      }
      const { latex } = await res.json();
      setCode(
        latex
          .replace(/^```(?:latex|tex)?\s*/i, '')
          .replace(/\s*```\s*$/, '')
          .trim()
      );
    } catch (err) {
      setError(err.message || 'Something went wrong. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (!generated.current) {
      generated.current = true;
      generate();
    }
  }, []); // eslint-disable-line react-hooks/exhaustive-deps

  const handleRetry = () => {
    setCode('');
    setError('');
    generated.current = false;
    generate();
  };

  const handleCopy = async () => {
    await copyToClipboard(code);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const STEPS = [
    {
      n: 1,
      title: 'Copy the LaTeX code',
      body: 'Switch to the "LaTeX code" tab and click "Copy code" to copy the entire template.',
    },
    {
      n: 2,
      title: 'Open Overleaf',
      body: 'Go to overleaf.com → "New Project" → "Blank Project". Give it any name.',
      link: { href: 'https://www.overleaf.com/project/new', label: 'Open Overleaf →' },
    },
    {
      n: 3,
      title: 'Paste and replace',
      body: 'Select all the default content in the editor (Ctrl+A) and paste your copied code.',
    },
    {
      n: 4,
      title: 'Review and recompile',
      body: 'The AI has filled in all sections. Scan for anything to tweak, then hit the green "Recompile" button.',
    },
    {
      n: 5,
      title: 'Download your PDF',
      body: "Hit 'Download PDF' in Overleaf. It's ATS-proven and recruiter-ready.",
    },
  ];

  return (
    <div className="export-panel-body export-panel-body--flush">
      {/* Tab bar */}
      <div className="export-tab-bar">
        <div className="export-tabs">
          {[
            { key: 'code', label: 'LaTeX code' },
            { key: 'instructions', label: 'How to use' },
          ].map(t => (
            <button
              key={t.key}
              onClick={() => setTab(t.key)}
              className={`export-tab ${tab === t.key ? 'active' : ''}`}
            >
              {t.label}
            </button>
          ))}
        </div>
        {tab === 'code' && (
          <div className="export-tab-actions">
            {error && (
              <button onClick={handleRetry} className="export-retry-btn export-retry-btn--inline">
                ↺ Retry
              </button>
            )}
            {code && !loading && (
              <CopyButton onClick={handleCopy} copied={copied} label="Copy code" copiedLabel="Copied!" />
            )}
          </div>
        )}
      </div>

      {/* Code tab */}
      {tab === 'code' && (
        <>
          {loading && (
            <LoadingSpinner
              message="Building your LaTeX resume…"
              sub="Usually takes a few seconds"
            />
          )}
          {!loading && error && <ErrorState message={error} onRetry={handleRetry} />}
          {!loading && !error && code && (
            <>
              <div className="export-notice export-notice--success">
                <span className="export-notice-icon">✓</span>
                <p>LaTeX ready — complete resume with all your data populated.</p>
              </div>
              <pre className="export-code-block export-code-block--latex">{code}</pre>
            </>
          )}
        </>
      )}

      {/* Instructions tab */}
      {tab === 'instructions' && (
        <div className="export-instructions">
          {STEPS.map(step => (
            <div key={step.n} className="export-step">
              <span className="export-step-num">{step.n}</span>
              <div>
                <p className="export-step-title">{step.title}</p>
                <p className="export-step-body">{step.body}</p>
                {step.link && (
                  <a
                    href={step.link.href}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="export-step-link"
                  >
                    {step.link.label}
                  </a>
                )}
              </div>
            </div>
          ))}
          <div className="export-notice export-notice--info">
            <span className="export-notice-icon">💡</span>
            <p>
              <strong>Why LaTeX?</strong> LaTeX produces typographically perfect output that looks
              the same on every machine. ATS scanners parse LaTeX-generated PDFs more reliably than
              Word or Google Docs exports. Jake's resume template is the most popular ATS-friendly
              LaTeX template on Overleaf.
            </p>
          </div>
        </div>
      )}
    </div>
  );
}

